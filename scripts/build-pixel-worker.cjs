'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const modules = ['color', 'mard-palettes', 'color-library', 'palette', 'pixel-denoise', 'pixel'];
function bundle() {
  const code = ['self.window = self;', ...modules.map(name => fs.readFileSync(path.join(root, 'js', name + '.js'), 'utf8')),
    fs.readFileSync(path.join(root, 'js/pixel-worker.js'), 'utf8').replace(/^importScripts\([^\n]*\);\r?$/m, '')].join('\n');
  return '/* Generated by node scripts/build-pixel-worker.cjs. Enables offline file:// workers. */\nwindow.PixelWorkerSource = ' + JSON.stringify(code) + ';\n';
}
if (require.main === module) fs.writeFileSync(path.join(root, 'js/pixel-worker-bundle.js'), bundle());
module.exports = { bundle };
